#!/usr/bin/env python3
"""Generate wiki/proposals/index.md: the stage list of ALL ECMA-402 proposals.

Source of truth is the canonical tc39/proposals tables under
raw/proposals/ecma402/ (README.md = Stage 3/2.7/2/1, finished-proposals.md =
Stage 4, stage-0-proposals.md, inactive-proposals.md). They are the precedence
source for a proposal's current stage and champion. This catalog is a
generated artifact: do NOT edit the output by hand. It is regenerated by the
Update workflow (after pulling raw/proposals).

ECMA-402 has few proposals (a few dozen), so every stage is listed in full,
including all of Stage 4 with its Expected Publication Year. Stage 4 rows
whose publication year is the current year or later are flagged as not yet in
a ratified edition.

Deep-read wiki pages (wiki/proposals/<slug>.md) are linked when their
frontmatter title (or an ALIASES entry) matches the canonical title; other
proposals link to their proposal repo.
"""

import datetime
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROP = ROOT / "raw" / "proposals" / "ecma402"
WIKI_PROP = ROOT / "wiki" / "proposals"
OUT = WIKI_PROP / "index.md"

CURRENT_YEAR = datetime.date.today().year

LINK = re.compile(r"\[([^\]]+)\](?: ?\[([^\]]*)\]|\(([^)]*)\))?")
REFDEF = re.compile(r"^\[([^\]]+)\]:\s*(\S+)", re.MULTILINE)
STAGE_HEADER = re.compile(r"^###\s*Stage\s*([0-9.]+)")
ROW = re.compile(r"^\|\s*\[")
YEAR = re.compile(r"\b(20\d{2})\b")

ORDER = ["4", "3", "2.7", "2", "1", "0", "inactive"]
LABEL = {
    "4": "Stage 4 (finished)",
    "3": "Stage 3",
    "2.7": "Stage 2.7",
    "2": "Stage 2",
    "1": "Stage 1",
    "0": "Stage 0",
    "inactive": "Inactive / Withdrawn",
}

# Canonical titles that don't normalize to the wiki page title. Keyed by
# norm(canonical title) -> wiki filename. Extend when a deep-read page's title
# diverges from tc39/proposals' wording.
ALIASES = {
    "intleraandmonthcodeproposal": "intl-era-month-code.md",
    "keeptrailingzerosinintlnumberformatandintlpluralrules": "intl-keep-trailing-zeros.md",
    "exploreassociatingaunitwithanumber": "intl-unit-protocol.md",
    "intlsegmenterunicodesegmentationinjavascript": "intl-segmenter.md",
}


def norm(t):
    return re.sub(r"[^a-z0-9]", "", t.lower())


def plain(cell):
    """Cell text without markdown/HTML noise."""
    t = re.sub(r"<br\s*/?>", ", ", cell)
    t = re.sub(r"<[^>]+>", "", t)
    t = LINK.sub(lambda m: m.group(1), t)
    return re.sub(r"\s+", " ", t.replace("`", "")).strip(" .,")


def title_and_url(cell, refs):
    m = LINK.search(cell)
    if not m:
        return plain(cell), None
    title = m.group(1).replace("`", "").strip()
    if m.group(3):
        return title, m.group(3)
    key = (m.group(2) or m.group(1)).lower()
    return title, refs.get(key)


def read(path):
    return path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""


def refs_of(text):
    return {k.lower(): v for k, v in REFDEF.findall(text)}


def parse_readme():
    text = read(PROP / "README.md")
    refs = refs_of(text)
    out = []
    stage = None
    for line in text.splitlines():
        h = STAGE_HEADER.match(line.strip())
        if h:
            stage = h.group(1)
            continue
        if ROW.match(line) and stage:
            c = line.split("|")
            title, url = title_and_url(c[1], refs)
            out.append({"stage": stage, "title": title, "url": url, "champion": plain(c[3]), "note": ""})
    return out


def parse_flat(fname, stage):
    text = read(PROP / fname)
    refs = refs_of(text)
    out = []
    for line in text.splitlines():
        if not ROW.match(line):
            continue
        c = line.split("|")
        title, url = title_and_url(c[1], refs)
        row = {"stage": stage, "title": title, "url": url, "champion": "", "note": "", "year": None}
        if stage == "inactive":
            row["champion"] = plain(c[2])
            row["note"] = plain(c[3])
        else:
            row["champion"] = plain(c[3])
        if stage == "4":
            ym = YEAR.search(c[-2]) if len(c) >= 2 else None
            row["year"] = int(ym.group(1)) if ym else None
        out.append(row)
    return out


def page_meta():
    """filename -> (title, frontmatter text) for deep-read pages."""
    out = {}
    for pf in sorted(WIKI_PROP.glob("*.md")):
        if pf.name == "index.md":
            continue
        fm = re.search(r"^---\n(.*?)\n---", read(pf), re.DOTALL)
        t = re.search(r"^title:\s*(.+)$", fm.group(1), re.MULTILINE) if fm else None
        if t:
            out[pf.name] = (t.group(1).strip(), fm.group(1))
    return out


def fm_field(fm, key):
    m = re.search(rf"^{key}:\s*(.+)$", fm, re.MULTILINE)
    return m.group(1).strip().strip('"') if m else ""


def wiki_page_map():
    m = {}
    for pf in WIKI_PROP.glob("*.md"):
        if pf.name == "index.md":
            continue
        fm = re.search(r"^---\n(.*?)\n---", read(pf), re.DOTALL)
        t = re.search(r"^title:\s*(.+)$", fm.group(1), re.MULTILINE) if fm else None
        if t:
            m[norm(t.group(1).strip())] = pf.name
    for alias_norm, fname in ALIASES.items():
        if (WIKI_PROP / fname).exists():
            m[alias_norm] = fname
    return m


def esc(t):
    return t.replace("|", "\\|")


def main():
    rows = parse_readme()
    rows += parse_flat("finished-proposals.md", "4")
    rows += parse_flat("stage-0-proposals.md", "0")
    rows += parse_flat("inactive-proposals.md", "inactive")
    pages = wiki_page_map()

    by_stage = {}
    for r in rows:
        by_stage.setdefault(r["stage"], []).append(r)

    out = [
        "# ECMA-402 proposal stage index",
        "",
        "> **Generated.** `tools/extract_proposals.py` builds this from `raw/proposals/ecma402/` (canonical). "
        "Do not edit by hand (regenerated whenever Update pulls `raw/proposals`).",
        "> Ingested proposals link to their wiki page (**bold**); the rest link to their proposal repo and are catalog-only here.",
        f"> Stage 4 rows with publication year {CURRENT_YEAR} or later are marked ⏳ (not yet in a ratified ECMA-402 edition).",
        f"> Total: {len(rows)} proposals.",
        "",
    ]
    for stage in ORDER:
        items = by_stage.get(stage)
        if not items:
            continue
        if stage == "4":
            items.sort(key=lambda r: (-(r["year"] or 0), r["title"].lower()))
        else:
            items.sort(key=lambda r: r["title"].lower())
        out.append(f"## {LABEL[stage]} ({len(items)})")
        out.append("")
        extra = {"4": "Publication", "inactive": "Rationale"}.get(stage)
        out.append("| Proposal | Champion |" + (f" {extra} |" if extra else ""))
        out.append("| --- | --- |" + (" --- |" if extra else ""))
        for r in items:
            page = pages.get(norm(r["title"]))
            if page:
                label = f"**[{esc(r['title'])}]({page})**"
            elif r["url"]:
                label = f"[{esc(r['title'])}]({r['url']})"
            else:
                label = esc(r["title"])
            cells = [label, esc(r["champion"])]
            if stage == "4":
                y = r["year"]
                cells.append(f"{y} ⏳" if y and y >= CURRENT_YEAR else str(y or ""))
            elif stage == "inactive":
                cells.append(esc(r["note"]))
            out.append("| " + " | ".join(cells) + " |")
        out.append("")

    # Deep-read pages of ECMA-262 proposals (not in the ECMA-402 tables).
    linked = {pages.get(norm(r["title"])) for r in rows}
    extra = [(f, t, fm) for f, (t, fm) in page_meta().items() if f not in linked]
    if extra:
        out.append(f"## Related ECMA-262 proposals (ingested) ({len(extra)})")
        out.append("")
        out.append("> Not in `raw/proposals/ecma402/`; stage and champions come from the page frontmatter "
                   "(canonical: the ECMA-262 tables in `raw/proposals/`).")
        out.append("")
        out.append("| Proposal | Champion | Stage |")
        out.append("| --- | --- | --- |")
        for f, t, fm in sorted(extra, key=lambda x: x[1].lower()):
            champs = fm_field(fm, "champions").strip("[]")
            out.append(f"| **[{esc(t)}]({f})** | {esc(champs)} | {fm_field(fm, 'current_stage')} |")
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out).rstrip("\n") + "\n", encoding="utf-8")
    counts = ", ".join(f"{s}:{len(by_stage.get(s, []))}" for s in ORDER)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} proposals ({counts}), {len(pages)} wiki pages linked")


if __name__ == "__main__":
    main()
